def weekly_plan(score):

    if score >= 80:

        return [

            "Monday : 3 Hours Study",

            "Tuesday : Coding Practice",

            "Wednesday : Revision",

            "Thursday : Mock Test",

            "Friday : Weak Subject",

            "Saturday : Previous Papers",

            "Sunday : Revision + Rest"

        ]

    elif score >= 60:

        return [

            "Study 5 Hours Daily",

            "Mock Test Every Saturday",

            "Revise Daily",

            "Practice Coding 1 Hour"

        ]

    else:

        return [

            "Study 6 Hours Daily",

            "Revise 2 Hours",

            "Practice Questions Daily",

            "Reduce Mobile Usage",

            "Take Weekly Mock Tests"

        ]